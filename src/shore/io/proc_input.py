def write_proc_input(
    grd_path: str | Path,
    out_path: str | Path,
    *,
    np: int = 1,
    proc_assignment: dict[int, int] | None = None,
    group_assignment: dict[int, int] | None = None,
    body_assignment: dict[int, int] | None = None,
    header_comment: str = "generated by SHORE",
) -> tuple[Path, BalanceSummary]:
    """Write a ``proc.input`` file from a SHORE-generated ``.grd``.

    Block ordering and weights come from ``grd_path`` — block 1 in the
    output is block 1 in the ``.grd``, with weight ``ni * nj * nk``
    (cell count).  When ``proc_assignment`` is omitted and ``np > 1``,
    blocks are distributed across ``range(np)`` by greedy
    weight-balanced assignment (descending block weight; place each
    on the least-loaded rank).

    Parameters
    ----------
    grd_path :
        Path to a SHORE / Xall ``.grd`` file.  Header is read for the
        block count and per-block ``(ni, nj, nk)`` cell counts; the
        coordinate payload is not touched.
    out_path :
        Output ``proc.input`` path.
    np :
        Total MPI rank count.  Default ``1`` (serial).  Must be ``>= 1``.
    proc_assignment :
        Optional explicit ``{block_idx (1-based) → proc (0-based)}`` map.
        Any block not listed gets the greedy-balanced default.  Procs
        outside ``range(np)`` are rejected.
    group_assignment :
        Optional ``{block_idx → group}`` map.  Default ``0`` for every
        block.
    body_assignment :
        Optional ``{block_idx → body}`` map.  Default ``0`` for every
        block.
    header_comment :
        Free-form text written on header line 1.  Default
        ``"generated by SHORE"``.

    Returns
    -------
    tuple[Path, BalanceSummary]
        The actual output path and the per-rank load summary.

    Raises
    ------
    ParameterError
        If ``np < 1``, an assignment dict references an unknown block
        index, or ``proc_assignment`` references a rank outside
        ``range(np)``.
    FileNotFoundError, ValueError
        Forwarded from :func:`read_grd_metadata`.
    """
    if np < 1:
        raise ParameterError(f"write_proc_input: np must be >= 1, got {np}")

    shapes = read_grd_metadata(grd_path)
    n = len(shapes)
    weights = [ni * nj * nk for ni, nj, nk in shapes]

    procs = _resolve_proc_assignment(weights, np, proc_assignment, n)
    groups = _resolve_int_assignment("group_assignment", group_assignment, n, default=0)
    bodies = _resolve_int_assignment("body_assignment", body_assignment, n, default=0)

    # Build the comment column from per-block weight + first parent label
    # if available.  We only have the weight here.
    comments = [f"weight={w}" for w in weights]

    out = Path(out_path)
    _write_proc_input_file(
        out,
        groups=groups,
        bodies=bodies,
        procs=procs,
        comments=comments,
        header_comment=header_comment,
    )

    summary = _build_summary(weights, procs, np)
    return out, summary


