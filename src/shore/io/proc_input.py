"""Xall ``proc.input`` writer + merger.

``proc.input`` is the runtime work-distribution descriptor Xall reads
at MPI startup.  It maps each block to an MPI rank and carries the
per-block ``group`` (rigid-body group) and ``body`` (corpo) indices
the solver's force/moment integration needs.

This file is a sibling of the chimera descriptor ``cc.par``, not a
downstream artefact: ``cc.par`` is consumed by the overset
preprocessor (which emits the runtime artefacts the solver actually
uses), while ``proc.input`` is consumed directly by Xall.

File format
-----------
Plain ASCII, free-format, parsed by Fortran list-directed
``read(*,*)``.  7-line header + N block records:

    <line 1: free-form comment, e.g. "generated by SHORE">
    <blank>
    <blank>
    <N>  number of blocks
    <blank>
    <blank>
    <column-header line, free-form>
    <block_idx>  <group>  <body>  <proc>  ! optional comment
    ...                                        x N

Block records carry exactly 4 numeric columns; the trailing
``! ...`` comment is advisory (the Fortran reader stops at column 4).

References
----------
Reader (authoritative): ``Xnavis-projects/Xnavis/Solver/src/input.f90``,
lines 45-119.

Writers in the wild (for context): ``LoadBalance/src/Lib_Balance.F90``
(``save_proc_input``) and
``overset-exploded/src/lib/overset_exploded_library.F90``
(``save_proc_input``).

Block indexing comes from the ``.grd`` file order — block 1 in
``proc.input`` is block 1 in the ``.grd``.  See
:func:`shore.io.grd.read_grd_metadata` for the per-block cell counts
this module uses as load-balancing weights.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from shore.exceptions import ParameterError
from shore.io.grd import read_grd_metadata

# ---------------------------------------------------------------------------
# Public types
# ---------------------------------------------------------------------------


@dataclass
class BalanceSummary:
    """One-screen report of the load distribution in a generated proc.input.

    Returned by :func:`write_proc_input` and used by the CLI to print
    the balance summary on stderr for parallel runs.

    Attributes
    ----------
    n_blocks :
        Total block count.
    np :
        Total MPI rank count.
    per_rank_blocks :
        Block count per rank, indexed by 0-based rank.
    per_rank_cells :
        Cell-count (work) per rank, indexed by 0-based rank.  Set to
        all-zero by :func:`merge_proc_input`, which has no access to
        per-block weights (``proc.input`` doesn't store them).
    imbalance :
        ``(max - min) / mean`` of ``per_rank_cells``, in fractional
        units.  0.0 = perfect balance.  Computed only when ``np > 1``
        and ``cells_known``; ``0.0`` for serial (``np == 1``) runs.
    cells_known :
        ``True`` for :func:`write_proc_input` (which reads weights from
        the ``.grd``); ``False`` for :func:`merge_proc_input` (which
        only sees block-to-rank assignments).  When ``False``, the
        ``format()`` rendering omits the cell count and imbalance so
        it doesn't suggest a wrong work-balance picture.
    """

    n_blocks: int
    np: int
    per_rank_blocks: list[int]
    per_rank_cells: list[int]
    imbalance: float
    cells_known: bool = True

    def format(self) -> str:
        """Render a human-readable multi-line summary.

        With cell-count weights available::

            proc.input: 11 blocks across 4 ranks
              rank 0: 3 blocks, 1.84M cells (28.1%)
              ...
              imbalance: 4.5%

        Without (e.g. the merger output)::

            proc.input: 11 blocks across 4 ranks
              rank 0: 3 blocks
              rank 1: 4 blocks
              ...
        """
        lines = [f"proc.input: {self.n_blocks} blocks across {self.np} ranks"]
        if self.cells_known:
            total_cells = sum(self.per_rank_cells)
            for r, (nb, nc) in enumerate(
                zip(self.per_rank_blocks, self.per_rank_cells, strict=True)
            ):
                pct = 100.0 * nc / total_cells if total_cells > 0 else 0.0
                lines.append(f"  rank {r}: {nb} blocks, {_fmt_cells(nc)} cells ({pct:.1f}%)")
            if self.np > 1:
                lines.append(f"  imbalance: {self.imbalance * 100:.1f}%")
        else:
            for r, nb in enumerate(self.per_rank_blocks):
                lines.append(f"  rank {r}: {nb} blocks")
        return "\n".join(lines)


