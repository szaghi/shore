def merge_proc_input(
    inputs: list[str | Path],
    out: str | Path,
    *,
    grd_path: str | Path | None = None,
    header_comment: str = "merged by SHORE",
) -> tuple[Path, BalanceSummary]:
    """Concatenate multiple ``proc.input`` files into one.

    Block indices shift by the cumulative block count of preceding
    inputs, mirroring :func:`shore.io.grd.merge_grd`.  ``group``,
    ``body``, and ``proc`` columns pass through verbatim — the merger
    does **not** re-run load balancing or renumber bodies / groups
    across components; collisions are the user's choice.

    Invoke ``merge_proc_input`` and :func:`shore.io.grd.merge_grd`
    **as a pair, with the same input ordering** — block-indices in
    ``proc.input`` are 1-based positions into the merged ``.grd``'s
    block list.

    Parameters
    ----------
    inputs :
        Two-or-more input ``proc.input`` paths.
    out :
        Output path.
    grd_path :
        Optional path to the merged ``.grd``.  When supplied, the
        returned :class:`BalanceSummary` carries real cell counts and
        the meaningful imbalance figure (``cells_known=True``); when
        ``None``, the summary falls back to per-rank block counts only
        (``cells_known=False``) because ``proc.input`` itself doesn't
        store per-block weights.
    header_comment :
        Free-form text written on header line 1 of the merged file.

    Returns
    -------
    tuple[Path, BalanceSummary]
        The actual output path and the per-rank load summary across
        all merged blocks.

    Raises
    ------
    ValueError
        If ``inputs`` has fewer than 2 entries.
    FileNotFoundError
        If any input path does not exist, or ``grd_path`` is supplied
        and missing.
    ParameterError
        If any input file is malformed, or the merged block count
        disagrees with the ``grd_path`` block count.
    """
    if len(inputs) < 2:
        raise ValueError(f"merge_proc_input: need at least 2 input files, got {len(inputs)}")

    parsed = [_read_proc_input(Path(p)) for p in inputs]

    merged_groups: list[int] = []
    merged_bodies: list[int] = []
    merged_procs: list[int] = []
    merged_comments: list[str] = []
    for stem_idx, records in enumerate(parsed):
        for _block_idx, group, body, proc, comment in records:
            merged_groups.append(group)
            merged_bodies.append(body)
            merged_procs.append(proc)
            # Strip a trailing ``.proc`` from the input stem (typical for
            # ``wall.proc.input`` etc.) so the merged comment reads e.g.
            # ``wall: weight=...`` instead of ``wall.proc: weight=...``.
            stem = Path(inputs[stem_idx]).stem
            if stem.endswith(".proc"):
                stem = stem[: -len(".proc")]
            merged_comments.append(f"{stem}: {comment}" if comment else stem)

    out_path = Path(out)
    _write_proc_input_file(
        out_path,
        groups=merged_groups,
        bodies=merged_bodies,
        procs=merged_procs,
        comments=merged_comments,
        header_comment=header_comment,
    )

    n = len(merged_procs)
    np_total = max(merged_procs) + 1 if merged_procs else 1

    if grd_path is not None:
        # Real cell-balance summary, recomputed against the merged .grd.
        shapes = read_grd_metadata(grd_path)
        if len(shapes) != n:
            raise ParameterError(
                f"merge_proc_input: merged proc.input has {n} blocks but "
                f"{Path(grd_path).name} has {len(shapes)}; the .grd does not "
                "match the merged proc.input ordering."
            )
        weights = [ni * nj * nk for ni, nj, nk in shapes]
        summary = _build_summary(weights, merged_procs, np_total)
    else:
        # No .grd to read weights from.  Build a block-count-only summary
        # and mark cells_known=False so BalanceSummary.format() renders
        # just the per-rank block count rather than misleading cell totals.
        per_rank_blocks = [0] * np_total
        for p in merged_procs:
            per_rank_blocks[p] += 1
        summary = BalanceSummary(
            n_blocks=n,
            np=np_total,
            per_rank_blocks=per_rank_blocks,
            per_rank_cells=[0] * np_total,
            imbalance=0.0,
            cells_known=False,
        )
    return out_path, summary


