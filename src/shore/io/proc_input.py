def _resolve_proc_assignment(
    weights: list[int],
    np: int,
    explicit: dict[int, int] | None,
    n: int,
) -> list[int]:
    """Return the final per-block ``proc`` (0-based) list, length ``n``.

    Explicit assignments win; remaining blocks fill in by greedy
    weight-balanced assignment among the unassigned weight pool.
    """
    explicit = explicit or {}
    for k, v in explicit.items():
        if not (1 <= k <= n):
            raise ParameterError(
                f"write_proc_input: proc_assignment references block {k} (must be 1..{n})"
            )
        if not (0 <= v < np):
            raise ParameterError(
                f"write_proc_input: proc_assignment[{k}] = {v} is outside range(0, {np})"
            )

    procs: list[int | None] = [None] * n
    for k, v in explicit.items():
        procs[k - 1] = v

    if all(p is not None for p in procs):
        return [int(p) for p in procs]  # type: ignore[arg-type]

    # Greedy: rank loads start with the explicit assignments' contributions.
    rank_load = [0] * np
    for i, p in enumerate(procs):
        if p is not None:
            rank_load[p] += weights[i]

    # Place remaining blocks heaviest-first on the least-loaded rank.
    unassigned = sorted(
        ((weights[i], i) for i in range(n) if procs[i] is None),
        key=lambda wb: -wb[0],
    )
    for w, i in unassigned:
        r = min(range(np), key=lambda r: rank_load[r])
        procs[i] = r
        rank_load[r] += w

    return [int(p) for p in procs]  # type: ignore[arg-type]


def _resolve_int_assignment(
    name: str,
    explicit: dict[int, int] | None,
    n: int,
    *,
    default: int,
) -> list[int]:
    """Resolve a per-block int assignment dict to a length-``n`` list."""
    explicit = explicit or {}
    out = [default] * n
    for k, v in explicit.items():
        if not (1 <= k <= n):
            raise ParameterError(f"write_proc_input: {name} references block {k} (must be 1..{n})")
        out[k - 1] = int(v)
    return out


def _build_summary(weights: list[int], procs: list[int], np: int) -> BalanceSummary:
    """Compute the per-rank summary from per-block weights + assignments."""
    per_rank_blocks = [0] * np
    per_rank_cells = [0] * np
    for w, p in zip(weights, procs, strict=True):
        per_rank_blocks[p] += 1
        per_rank_cells[p] += w

    if np > 1 and per_rank_cells:
        mean = sum(per_rank_cells) / np
        imbalance = (max(per_rank_cells) - min(per_rank_cells)) / mean if mean > 0 else 0.0
    else:
        imbalance = 0.0

    return BalanceSummary(
        n_blocks=len(weights),
        np=np,
        per_rank_blocks=per_rank_blocks,
        per_rank_cells=per_rank_cells,
        imbalance=imbalance,
    )


def _write_proc_input_file(
    path: Path,
    *,
    groups: list[int],
    bodies: list[int],
    procs: list[int],
    comments: list[str],
    header_comment: str,
) -> None:
    n = len(groups)
    with path.open("w", encoding="ascii") as f:
        f.write(f"{header_comment}\n")
        f.write("\n")
        f.write("\n")
        f.write(f"{n} number of blocks\n")
        f.write("\n")
        f.write("\n")
        f.write(" block - group - body - processor [comment]\n")
        for i in range(n):
            cmt = comments[i] if i < len(comments) and comments[i] else ""
            line = f"{i + 1:6d} {groups[i]:6d} {bodies[i]:6d} {procs[i]:6d}"
            if cmt:
                line += f" ! {cmt}"
            f.write(line + "\n")


def _read_proc_input(path: Path) -> list[tuple[int, int, int, int, str]]:
    """Parse a ``proc.input`` file.

    Returns
    -------
    list[tuple[int, int, int, int, str]]
        ``(block_idx, group, body, proc, comment)`` per record.

    Raises
    ------
    FileNotFoundError, ParameterError
    """
    if not path.exists():
        raise FileNotFoundError(f"merge_proc_input: {path} not found")
    lines = path.read_text(encoding="ascii", errors="replace").splitlines()
    if len(lines) < 8:
        raise ParameterError(
            f"merge_proc_input: {path} is too short (need >= 8 lines, got {len(lines)})"
        )

    # Line 4 holds the block count (only the leading integer is parsed).
    try:
        n_blocks = int(lines[3].split()[0])
    except (IndexError, ValueError) as e:
        raise ParameterError(
            f"merge_proc_input: {path} line 4 does not start with an integer block count"
        ) from e

    body_start = 7
    body_end = body_start + n_blocks
    if body_end > len(lines):
        raise ParameterError(
            f"merge_proc_input: {path} reports {n_blocks} blocks but has only "
            f"{len(lines) - body_start} body lines"
        )

    out: list[tuple[int, int, int, int, str]] = []
    for ln_idx in range(body_start, body_end):
        line = lines[ln_idx]
        # Split off any trailing "! comment".
        head, _, tail = line.partition("!")
        comment = tail.strip()
        toks = head.split()
        if len(toks) < 4:
            raise ParameterError(
                f"merge_proc_input: {path} line {ln_idx + 1} has fewer than 4 columns"
            )
        try:
            block_idx, group, body, proc = (int(t) for t in toks[:4])
        except ValueError as e:
            raise ParameterError(
                f"merge_proc_input: {path} line {ln_idx + 1} has non-integer values"
            ) from e
        out.append((block_idx, group, body, proc, comment))

    return out


def _fmt_cells(n: int) -> str:
    """Format a cell count for the balance summary (e.g. ``1.84M``)."""
    if n >= 1_000_000:
        return f"{n / 1_000_000:.2f}M"
    if n >= 1_000:
        return f"{n / 1_000:.1f}k"
    return str(n)
